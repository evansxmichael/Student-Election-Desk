export function getStudentGender(student: Partial<Student>): GenderType {
  if (student.gender === 'Female' || student.gender === 'Male') {
    return student.gender;
  }
  const name = (student.name || '').trim().toLowerCase();
  return VERIFIED_FEMALE_NAMES.has(name) ? 'Female' : 'Male';
}
